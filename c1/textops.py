"""THEORY §74: does the stable latent need a pretrained LM? Paraphrase transfer of the latent machine.

Task: 3 boxes, S3 generated by the 3 transpositions; start = identity (code 0); final answer = the arrangement (6-way),
the only label. State update s <- a o s ((a o s)[i] = a[s[i]], as c1/core.py). Ops are text:
  train  " swap i j" (i < j)          F1 " swap j i"                F2 " swap one and two"
  F3     " exchange boxes 1 and 2"     F4 " swap the first and second"
  pos    " Swap 1 2" (casing)          neg " copy 1 2" (verb control)
Cell (PF-std as §72b/§73): transition call [code_emb, op-text tokens, " step"]; h_code at position 0, h_op at the step
marker (pool: mean over the op-text span); W ReLU((U std(h_code)) * (V std(h_op))); decoder [code_emb, " answer"] ->
ans_head(std(h_dec)). std = per-coordinate standardisation with statistics from the TRAINING table (M x 3 transition
calls; M decoder calls), computed from the current table during training, frozen after training and applied unchanged
to every held-out phrasing (eps 1e-5). sigma-floor variant: sigma' = max(sigma, median(sigma) / 10).
Arms: pfstd (frozen pretrained GPT-2), rfstd (frozen random-init), dense (no transformer: h_code = code, h_op = code +
sum of op-token embeddings, h_dec = code), pool (pfstd with h_op = mean over the op span).
Training: exact marginalisation over the 3-op tables, curriculum lengths {1}, {1,2}, {1,2,4}, {1,2,4,8} in 4 stages,
tau 4 -> 1 over the first half, AdamW lr 1e-4 on codes and heads (GPT-2 frozen), 8,000 updates, bs 512.
Eval (eval.json): training-phrasing certificate (product automaton) + hard accuracy N 8-128; per family: paraphrase
agreement over the reachable codes (frozen sigma and sigma'), family certificate, hard accuracy N 8-128 with every op
paraphrased (table rollout = the real calls, which are deterministic per (code, op)); feature diagnostic at init and end
(raw cosine and nearest-neighbour rank vs the 3 training ops at the same code); GPT-2 cosine of " one" vs " 1".
    python -m c1.textops --arm pfstd --seed 2021 --out c1/runs/p74_pfstd_s2021 [--device cuda:0]
"""
import argparse
import itertools
import json
import math
import os
import sys
import time

import numpy as np
import tiktoken
import torch
import torch.nn as nn
import torch.nn.functional as F

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
from boxes.core import GPT2KV  # noqa: E402
from c1.core import gpt2_random_sd  # noqa: E402

ENC = tiktoken.get_encoding("gpt2")
PERMS = sorted(itertools.permutations(range(3)))
COMP = np.array([[PERMS.index(tuple(a[s[i]] for i in range(3))) for s in PERMS] for a in PERMS])   # COMP[a, s] = a o s
PAIRS = [(1, 2), (1, 3), (2, 3)]                                     # 1-based box pairs, i < j


def transposition(i, j):
    p = list(range(3)); p[i - 1], p[j - 1] = p[j - 1], p[i - 1]; return PERMS.index(tuple(p))


OPS = [transposition(i, j) for i, j in PAIRS]                         # group element of each op index 0..2
NUM = {1: "one", 2: "two", 3: "three"}; ORD = {1: "first", 2: "second", 3: "third"}
FAMILIES = {
    "train": lambda i, j: f" swap {i} {j}", "F1": lambda i, j: f" swap {j} {i}",
    "F2": lambda i, j: f" swap {NUM[i]} and {NUM[j]}", "F3": lambda i, j: f" exchange boxes {i} and {j}",
    "F4": lambda i, j: f" swap the {ORD[i]} and {ORD[j]}", "pos": lambda i, j: f" Swap {i} {j}",
    "neg": lambda i, j: f" copy {i} {j}"}
STEP, ANS = ENC.encode(" step")[0], ENC.encode(" answer")[0]
M = 24


def truth(ops):
    s = 0
    for a in ops:
        s = COMP[OPS[a], s]
    return int(s)


class TextCell(nn.Module):
    def __init__(self, arm, seed, hid=256):
        super().__init__()
        self.arm = arm
        if arm != "dense":
            sd = torch.load(os.path.join(ROOT, "prosqa", "ckpt", "gpt2_pretrained.bin"), map_location="cpu", weights_only=True) \
                if arm in ("pfstd", "pool") else gpt2_random_sd(seed)
            self.g = GPT2KV(sd); self.g.requires_grad_(False)
            wte = self.g.w("wte.weight")
        else:
            sd = torch.load(os.path.join(ROOT, "prosqa", "ckpt", "gpt2_pretrained.bin"), map_location="cpu", weights_only=True)
            self.register_buffer("wte", sd["wte.weight"].float().clone()); self.g = None; wte = self.wte
        self.code = nn.Parameter(0.14 * torch.randn(M, 768))
        self.U, self.V, self.W = nn.Linear(768, hid), nn.Linear(768, hid), nn.Linear(hid, M)
        self.ans_head = nn.Linear(768, 6)
        self.op_tok = {f: [ENC.encode(FAMILIES[f](i, j)) for i, j in PAIRS] for f in FAMILIES}
        self.stats = None                                             # frozen after training
        self.sigma_floor = False

    def emb(self, ids):
        return (self.g.embed(ids) if self.g is not None else self.wte[ids])

    def raw(self, codes, op, fam):
        """raw (h_code, h_op) for a batch of codes with one op in one family."""
        dev = self.code.device; tok = torch.tensor(self.op_tok[fam][op], device=dev)
        if self.arm == "dense":
            ope = self.emb(tok).sum(0)
            return self.code[codes], self.code[codes] + ope[None]
        B = len(codes)
        x = torch.cat([self.code[codes][:, None], self.emb(tok)[None].expand(B, -1, -1),
                       self.emb(torch.full((B, 1), STEP, device=dev))], 1)
        h, _ = self.g(x)
        hop = h[:, 1:-1].mean(1) if self.arm == "pool" else h[:, -1]
        return h[:, 0], hop

    def raw_dec(self, codes):
        if self.arm == "dense":
            return self.code[codes]
        dev = self.code.device
        x = torch.stack([self.code[codes], self.emb(torch.full_like(codes, ANS))], 1)
        h, _ = self.g(x)
        return h[:, -1]

    def train_table_raw(self):
        dev = self.code.device; codes = torch.arange(M, device=dev)
        hc, ho = zip(*[self.raw(codes, a, "train") for a in range(3)])
        return torch.cat(hc), torch.cat(ho), self.raw_dec(codes)

    def compute_stats(self):
        with torch.no_grad():
            hc, ho, hd = self.train_table_raw()
            self.stats = tuple((t.mean(0), t.std(0) + 1e-5) for t in (hc, ho, hd))
        return self.stats

    def _sig(self, s):
        return torch.maximum(s, s.median() / 10) if self.sigma_floor else s

    def logits_next(self, codes, op, fam, stats=None):
        hc, ho = self.raw(codes, op, fam); (mc, sc), (mo, so), _ = stats or self.stats
        return self.W(torch.relu(self.U((hc - mc) / self._sig(sc)) * self.V((ho - mo) / self._sig(so))))

    def logits_dec(self, codes, stats=None):
        hd = self.raw_dec(codes); _, _, (md, sd) = stats or self.stats
        return self.ans_head((hd - md) / self._sig(sd))

    def tables(self, tau):
        """training-time tables from the current (live) training table statistics."""
        hc, ho, hd = self.train_table_raw()
        st = tuple((t.mean(0), t.std(0) + 1e-5) for t in (hc, ho, hd))
        (mc, sc), (mo, so), (md, sd) = st
        lt = self.W(torch.relu(self.U((hc - mc) / sc) * self.V((ho - mo) / so))).view(3, M, M)
        return (lt / tau).log_softmax(-1), self.ans_head((hd - md) / sd).log_softmax(-1)


def marginal_loss(logT, logD, ops, y):
    B, N = ops.shape; la = torch.full((B, M), -math.inf, device=logT.device); la[:, 0] = 0.0
    for t in range(N):
        la = torch.logsumexp(la[:, :, None] + logT[ops[:, t]], 1)
    return -torch.logsumexp(la + logD[:, y].T, 1).mean()


@torch.no_grad()
def hard_tables(m, fam):
    dev = m.code.device; codes = torch.arange(M, device=dev)
    Th = torch.stack([m.logits_next(codes, a, fam).argmax(-1) for a in range(3)], 1).cpu().numpy()   # (M, 3)
    Dh = m.logits_dec(codes).argmax(-1).cpu().numpy()
    return Th, Dh


def reach(Th):
    seen, fr = {0}, [0]
    while fr:
        c = fr.pop()
        for a in range(3):
            if Th[c, a] not in seen:
                seen.add(int(Th[c, a])); fr.append(int(Th[c, a]))
    return sorted(seen)


def bad_pairs(Th, Dh):
    """Product-automaton BFS by length from (code 0, identity): every reachable (code, state) pair after >= 1 op with its
    first length reached, the decoded state and the true state, for the pairs that decode wrongly (Theory's request)."""
    first, frontier, L = {}, [(0, 0)], 0
    seen = set()
    while frontier:
        L += 1; nxt = []
        for c, st in frontier:
            for a in range(3):
                p = (int(Th[c, a]), int(COMP[OPS[a], st]))
                if p not in seen:
                    seen.add(p); first[p] = L; nxt.append(p)
        frontier = nxt
    return [{"code": c, "state": st, "first_length": first[(c, st)], "decoded": int(Dh[c]), "true": st}
            for (c, st) in sorted(first) if Dh[c] != st]


def certificate(Th, Dh):
    seen, fr, bad = set(), [(0, 0)], 0
    while fr:
        c, st = fr.pop()
        for a in range(3):
            nxt = (int(Th[c, a]), int(COMP[OPS[a], st]))
            if nxt not in seen:
                seen.add(nxt); fr.append(nxt); bad += int(Dh[nxt[0]] != nxt[1])
    return {"certified": bad == 0, "bad_pairs": bad, "reachable_pairs": len(seen)}


def table_acc(Th, Dh, rng, n=2000):
    out = {}
    for N in (8, 16, 32, 64, 128):
        ops = rng.integers(0, 3, (n, N)); c = np.zeros(n, int); s = np.zeros(n, int)
        for t in range(N):
            c = Th[c, ops[:, t]]; s = COMP[np.array(OPS)[ops[:, t]], s]
        out[str(N)] = float((Dh[c] == s).mean())
    return out


@torch.no_grad()
def feature_diag(m):
    """raw cosine of each family's h_op vs the training phrasing's h_op (same code, same op), and the nearest-neighbour
    rank of the true op among the 3 training ops (1 = correct), averaged over codes and ops."""
    dev = m.code.device; codes = torch.arange(M, device=dev)
    tr = torch.stack([m.raw(codes, a, "train")[1] for a in range(3)], 1)          # (M, 3, D)
    out = {}
    for f in FAMILIES:
        if f == "train":
            continue
        pa = torch.stack([m.raw(codes, a, f)[1] for a in range(3)], 1)
        cos_true = F.cosine_similarity(pa, tr, dim=-1).mean().item()
        sims = F.cosine_similarity(pa[:, :, None], tr[:, None], dim=-1)          # (M, 3 para op, 3 train op)
        rank = (sims > sims.gather(2, torch.arange(3, device=dev)[None, :, None].expand(M, 3, 1))).sum(-1).float() + 1
        out[f] = {"raw_cos_vs_same_op": cos_true, "nn_rank_mean": rank.mean().item(), "nn_rank1_share": (rank == 1).float().mean().item()}
    return out


@torch.no_grad()
def one_vs_1(m):
    if m.g is None:
        return None
    a, b = ENC.encode(" one")[0], ENC.encode(" 1")[0]; dev = m.code.device
    e = F.cosine_similarity(m.emb(torch.tensor([a], device=dev)), m.emb(torch.tensor([b], device=dev))).item()
    ha, _ = m.g(m.emb(torch.tensor([[a]], device=dev))); hb, _ = m.g(m.emb(torch.tensor([[b]], device=dev)))
    return {"wte_cos": e, "final_hidden_cos": F.cosine_similarity(ha[0, -1:], hb[0, -1:]).item()}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--arm", required=True, choices=["pfstd", "rfstd", "dense", "pool"])
    ap.add_argument("--seed", type=int, default=2021); ap.add_argument("--updates", type=int, default=8000)
    ap.add_argument("--bs", type=int, default=512); ap.add_argument("--lr", type=float, default=1e-4)
    ap.add_argument("--tau0", type=float, default=4.0)
    ap.add_argument("--device", default="cuda:0"); ap.add_argument("--out", required=True)
    a = ap.parse_args()
    torch.manual_seed(a.seed); rng = np.random.default_rng(a.seed); dev = a.device
    m = TextCell(a.arm, a.seed).to(dev)
    os.makedirs(a.out, exist_ok=True); json.dump(vars(a), open(os.path.join(a.out, "args.json"), "w", newline="\n"), indent=1)
    m.compute_stats(); diag0 = feature_diag(m); m.stats = None
    opt = torch.optim.AdamW([p for p in m.parameters() if p.requires_grad], lr=a.lr, weight_decay=0.0)
    log = open(os.path.join(a.out, "log.jsonl"), "w", newline="\n"); t0 = time.time(); hist = []
    for u in range(1, a.updates + 1):
        L = int(rng.choice((1, 2, 4, 8)[: min(3, (u - 1) * 4 // a.updates) + 1]))
        ops = rng.integers(0, 3, (a.bs, L)); y = np.array([truth(r) for r in ops])
        tau = 1.0 + (a.tau0 - 1.0) * max(0.0, 1.0 - (u - 1) / (0.5 * a.updates))
        logT, logD = m.tables(tau)
        loss = marginal_loss(logT, logD, torch.tensor(ops, device=dev), torch.tensor(y, device=dev))
        opt.zero_grad(); loss.backward(); torch.nn.utils.clip_grad_norm_(m.parameters(), 1.0); opt.step(); hist.append(loss.item())
        if u % 200 == 0 or u == a.updates:
            log.write(json.dumps({"update": u, "L": L, "loss": float(np.mean(hist)), "sec": round(time.time() - t0)}) + "\n"); log.flush(); hist = []
    train_sec = round(time.time() - t0)
    m.eval(); m.compute_stats()                                       # frozen training-table statistics from here on
    res = {"arm": a.arm, "seed": a.seed, "train_sec": train_sec}
    Th0, Dh = hard_tables(m, "train"); R = reach(Th0)
    res["train"] = {"certificate": certificate(Th0, Dh), "acc": table_acc(Th0, Dh, np.random.default_rng(7400)), "reachable_codes": R,
                    "bad_pairs": bad_pairs(Th0, Dh), "Th": Th0.tolist(), "Dh": Dh.tolist()}
    torch.save({k: v for k, v in m.state_dict().items() if not k.startswith(("g.", "wte"))}, os.path.join(a.out, "trainable.pt"))
    res["families"] = {}
    for floor in (False, True):
        m.sigma_floor = floor
        for f in FAMILIES:
            if f == "train":
                continue
            Th, Dh_f = hard_tables(m, f)
            agree = float(np.mean([Th[c, op] == Th0[c, op] for c in R for op in range(3)]))
            r = {"agreement": agree, "chance": 1 / max(1, len(R))}
            if not floor:
                r.update(certificate=certificate(Th, Dh_f), acc=table_acc(Th, Dh_f, np.random.default_rng(7401)))
            res["families"].setdefault(f, {})["sigma_floor" if floor else "frozen_sigma"] = r
    m.sigma_floor = False
    res["feature_diag"] = {"init": diag0, "end": feature_diag(m)}
    res["one_vs_1"] = one_vs_1(m)
    q = lambda t: [float(t.min()), float(t.median()), float(t.max())]
    res["sigma_min_med_max"] = {k: q(st[1]) for k, st in zip(("code", "op", "dec"), m.stats)}
    json.dump(res, open(os.path.join(a.out, "eval.json"), "w", newline="\n"), indent=1)
    print("EVAL", json.dumps({"train_cert": res["train"]["certificate"]["certified"],
                              "agree": {f: round(v["frozen_sigma"]["agreement"], 3) for f, v in res["families"].items()}}), flush=True)
    print("DONE", a.out, flush=True)


if __name__ == "__main__":
    main()
