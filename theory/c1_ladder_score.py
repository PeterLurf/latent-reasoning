"""THEORY §82 scoring: certificates per group (ge3 primary, std reference) and the coset-trap analysis of failures.

For a hard table (Th, Dh) the reachable (code, state) pairs from (0, e) define, for each state s, its code set. States that
share a code are merged; the merged classes (connected components) form a partition of the reachable states. A failure is
a COSET TRAP if that partition equals the right-coset partition {H g} of some proper subgroup H (subgroups generated by
<= 2 elements, theory/groups_extra.subgroups). Certified tables give singletons (H = 1); chance-like ones one block.
    python theory/c1_ladder_score.py [--dirs theory/results/c1_tab82 theory/results/c1_tab_local] [--out ...]
"""
import argparse
import glob
import json
import os
import sys

import numpy as np

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from c1_group import comp_table  # noqa: E402
from groups_extra import right_coset_partition, subgroups  # noqa: E402

_SUBS = {}


def partition(Th, Dh, COMP, e):
    A = COMP.shape[1]; seen, fr = set(), [(0, e)]
    while fr:
        c, st = fr.pop()
        for a in range(A):
            nx = (int(Th[c][a]), int(COMP[st, a]))
            if nx not in seen:
                seen.add(nx); fr.append(nx)
    parent = {}
    def find(x):
        while parent.setdefault(x, x) != x:
            x = parent[x]
        return x
    bycode = {}
    for c, s in seen:
        bycode.setdefault(c, []).append(s)
    for ss in bycode.values():
        for s in ss[1:]:
            parent[find(s)] = find(ss[0])
    blocks = {}
    for s in {s for _, s in seen}:
        blocks.setdefault(find(s), set()).add(s)
    return [frozenset(b) for b in blocks.values()], len({s for _, s in seen})


def coset_match(group, COMP, blocks):
    if group not in _SUBS:
        _SUBS[group] = [H for H in subgroups(COMP)]
    target = set(blocks)
    for H in _SUBS[group]:
        if set(right_coset_partition(COMP, H)) == target:
            return len(H)
    return None


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--dirs", nargs="*", default=["theory/results/c1_tab82", "theory/results/c1_tab_local"])
    ap.add_argument("--groups", nargs="*", default=["Z59", "Z60", "D30", "A4xZ5", "A5", "S4"])
    ap.add_argument("--out", default="theory/results/score_s82.json")
    a = ap.parse_args(); res = {}
    for g in a.groups:
        COMP, e, A = comp_table(g)
        for cur in ("ge3", "std"):
            files = sorted(f for d in a.dirs for f in glob.glob(os.path.join(d, "%s_%s_s*.json" % (g, cur))))
            rows = []
            for f in files:
                r = next(iter(json.load(open(f)).values()))
                if "table" not in r:
                    continue
                blocks, nreach = partition(r["table"], r["dec"], COMP, e)
                sizes = sorted((len(b) for b in blocks), reverse=True)
                H = coset_match(g, COMP, blocks) if not r["certified"] else 1
                rows.append({"file": os.path.basename(f), "certified": r["certified"], "acc128": round(r["acc"]["128"], 3),
                             "reached_states": nreach, "block_sizes": sizes[:6], "n_blocks": len(blocks), "coset_trap_H": H})
            if rows:
                k = sum(x["certified"] for x in rows)
                traps = [x["coset_trap_H"] for x in rows if not x["certified"]]
                res["%s_%s" % (g, cur)] = {"certified": k, "n": len(rows), "runs": rows}
                print("%-6s %-4s certified %d/%d | failures: coset-trap |H| %s | acc128 %s" % (
                    g, cur, k, len(rows), traps, [x["acc128"] for x in rows if not x["certified"]]))
    json.dump(res, open(a.out, "w", newline="\n"), indent=1)


if __name__ == "__main__":
    main()
