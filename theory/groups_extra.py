"""THEORY §82: extra groups as permutation groups (closure from generators), in the c1_group.comp_table convention
(state s, op a -> a o s with (a o s)[i] = a[s[i]]; the identity has index 0).
  Z60 (cyclic, 60 points), Z59 (cyclic, prime: no proper non-trivial subgroups), D30 (dihedral of order 60 on 30 points),
  A4xZ5 (A4 on points 0-3 times Z5 on points 4-8). Also subgroups() for the coset-trap analysis.
"""
import itertools

import numpy as np


def _cycle(n, off=0, N=None):
    N = N or n
    p = list(range(N))
    for i in range(n):
        p[off + i] = off + (i + 1) % n
    return tuple(p)


def _compose(a, s):                                  # (a o s)[i] = a[s[i]]
    return tuple(a[i] for i in s)


def closure(gens):
    e = tuple(range(len(gens[0])))
    G, frontier = [e], [e]
    seen = {e}
    while frontier:
        nxt = []
        for g in frontier:
            for h in gens:
                x = _compose(h, g)
                if x not in seen:
                    seen.add(x); G.append(x); nxt.append(x)
        frontier = nxt
    return G


def generators(name):
    if name == "Z60":
        return [_cycle(60)]
    if name == "Z59":
        return [_cycle(59)]
    if name == "D30":
        n = 30
        return [_cycle(n), tuple((-i) % n for i in range(n))]
    if name == "A4xZ5":
        N = 9
        a = list(range(N)); a[0], a[1], a[2] = 1, 2, 0                  # (0 1 2)
        b = list(range(N)); b[0], b[1], b[2], b[3] = 1, 0, 3, 2         # (0 1)(2 3)
        return [tuple(a), tuple(b), _cycle(5, 4, N)]
    raise KeyError(name)


EXTRA = {"Z60": 60, "Z59": 59, "D30": 60, "A4xZ5": 60}


def comp_table(name):
    G = closure(generators(name))
    assert len(G) == EXTRA[name], (name, len(G))
    idx = {g: i for i, g in enumerate(G)}
    COMP = np.array([[idx[_compose(G[a], G[s])] for a in range(len(G))] for s in range(len(G))])
    return COMP, 0, len(G)


def subgroups(COMP):
    """All subgroups generated by at most two elements (as frozensets of element indices), via the composition table."""
    n = COMP.shape[0]
    def close(gs):
        S, fr = {0}, [0]
        while fr:
            nx = []
            for x in fr:
                for g in gs:
                    y = int(COMP[x, g])
                    if y not in S:
                        S.add(y); nx.append(y)
            fr = nx
        return frozenset(S)
    subs = set()
    for a in range(n):
        subs.add(close([a]))
    for a, b in itertools.combinations(range(n), 2):
        subs.add(close([a, b]))
    return sorted(subs, key=len)


def right_coset_partition(COMP, H):
    """Right cosets H g = {h o g}: here 'op h applied after state g' is COMP[g, h] = h o g."""
    n = COMP.shape[0]; seen, parts = set(), []
    for g in range(n):
        if g not in seen:
            c = frozenset(int(COMP[g, h]) for h in H); parts.append(c); seen |= c
    return parts


if __name__ == "__main__":
    for nm in EXTRA:
        C, e, A = comp_table(nm)
        assert (C[0] == np.arange(A)).all() and sorted(C[:, 0]) == list(range(A))
        subs = subgroups(C)
        idxs = sorted({A // len(H) for H in subs if 1 < len(H) < A})
        print(nm, "order", A, "proper non-trivial subgroup indices", idxs[:12], "count", sum(1 < len(H) < A for H in subs))
