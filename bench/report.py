"""Collect bench/results/*.json and the published numbers in bench/literature.json into bench/LEADERBOARD.md.

    python -m bench.report

Per task: our runs (accuracy, 95% interval, accuracy by depth, mean compute), the no-reasoning baselines on the same
items, and published numbers. A published number is labelled "same test" only when the paper used the file this
harness loads; anything else is context, not a head-to-head result.
"""
import glob
import json
import os

from bench import tasks

ROOT = tasks.ROOT
B = os.path.join(ROOT, "bench")


def pct(x):
    return "—" if x is None else f"{100 * x:.1f}"


def main():
    res = [json.load(open(f)) for f in sorted(glob.glob(os.path.join(B, "results", "*.json")))]
    lit = json.load(open(os.path.join(B, "literature.json")))["entries"]
    out = ["# Reasoning benchmark leaderboard", "",
           "Generated by `python -m bench.report` from `bench/results/` and `bench/literature.json`. Accuracy in %; "
           "the interval is a 95% Wilson interval. † = published number not yet verified by Literature.", ""]
    for name, t in tasks.TASKS.items():
        rs = [r for r in res if r["task"] == name]
        ls = [e for e in lit if e["task"] == name]
        if not rs and not ls:
            continue
        out += [f"## {name}", "", f"{t.source}. Depth = {t.depth}.", ""]
        if rs:
            depths = sorted({d for r in rs for d in r["by_depth"]}, key=int)
            out += ["| Model | n | Acc | 95% CI | " + " | ".join(f"d{d}" for d in depths) + " | latent passes | gen tokens | commit |",
                    "|---|---|---|---|" + "---|" * len(depths) + "---|---|---|"]
            for r in sorted(rs, key=lambda r: -r["accuracy"]):
                bd = [pct(r["by_depth"].get(d, {}).get("acc")) for d in depths]
                ci = f"{pct(r['ci95'][0])}–{pct(r['ci95'][1])}"
                out.append(f"| `{r['model']}` | {r['n']} | **{pct(r['accuracy'])}** | {ci} | " + " | ".join(bd) +
                           f" | {r['mean_compute']['latent_passes']} | {r['mean_compute']['gen_tokens']} | {r['provenance']['commit']} |")
            b = rs[0].get("baselines_same_items", {})
            if b:
                out += ["", "No-reasoning baselines on the same items: " + ", ".join(f"{k} {pct(v)}" for k, v in b.items()) + "."]
            out.append("")
        if ls:
            out += ["Published:", "", "| System | Acc | Source | Same test? |", "|---|---|---|---|"]
            for e in ls:
                mark = "" if e.get("verified") else " †"
                out.append(f"| {e['system']} | {pct(e['acc'])}{mark} | {e['source']} | {'yes' if e['same_items'] else 'no'} |")
            out.append("")
    with open(os.path.join(B, "LEADERBOARD.md"), "w", newline="\n", encoding="utf-8") as f:
        f.write("\n".join(out) + "\n")
    print("\n".join(out))


if __name__ == "__main__":
    main()
